-- 匿名上传:给 skill 补"声明归属"两列。
--
-- 【为什么改】
-- 上传 skill 原本必须登录,归属人就是上传者(skill.owner_user_id = 当前登录人)。现在上传放开为匿名可用,
-- 于是出现了一种此前不存在的状态:包已经在平台上了,但还没有真实的归属人。
--
-- 【无主怎么表示:刻意不把 owner_user_id 改成可空】
-- V0002 已经为这个问题留下过答案 —— system 账号(id=1)刻意不持有任何 user_identity、永远登不进来,
-- 它存在的全部理由就是"让 owner_user_id / created_by_user_id 保持 NOT NULL,系统内置或导入的数据挂在一个
-- 真实存在的账号上,比把归属列做成可空、然后全链路特判要简单得多"。匿名上传沿用同一招:
-- owner_user_id = 1 即"无主 / 待认领"。
--
-- 也刻意**不**为匿名另开一个账号。system 现在承载的是"导入的、没有真实归属人的包",而导入的包被人认领
-- 接手恰恰是我们想要的行为,不是语义污染 —— 把两者统一成同一个状态反而更干净。顺带躲掉一个坑:
-- V0002 能硬编码 id=1 是因为 app_user 当时是全库唯一一张空表,V0005 没有这个前提,新插一个内置账号拿到的
-- id 在不同环境会不一样,而代码需要一个确定的值。
--
-- 【这两列是什么】
-- 匿名上传时可以自己填一个归属(姓名 + 可选工号)。它是**上传者自称的**,背后没有账号作背书,所以单独存两列,
-- 不混进 owner_user_id 指向的真实账号信息里:前端必须能区分"已认领的真实归属"与"未经核实的自称归属",
-- 若在数据层就把两者 COALESCE 成一个字段,这个区别会直接消失,前端再也无从还原。
--
-- 认领之后这两列**保留、不清空** —— "上传时自称了什么"是一条历史事实,清掉等于销毁线索。
--
-- 【列宽为什么照抄 app_user】
-- 与 app_user.display_name(64) / app_user.employee_no(32) 对齐:两边描述的是同一种东西(一个人的展示名与
-- 工号),区别只在一边有账号背书、一边没有。宽度不一致会让"把自称值与账号值比对"这类操作凭空多出截断风险。
--
-- 【安全性】
-- 两列都可空且无默认值,PostgreSQL 对这种 ADD COLUMN 只改 catalog、不重写表数据,也不做全表校验。
-- 现有数据(5 行)全部已有真实 owner,加列后 declared_owner_* 为 NULL —— 语义正确:它们不是匿名上传来的。

ALTER TABLE skill ADD COLUMN declared_owner_name        VARCHAR(64);
ALTER TABLE skill ADD COLUMN declared_owner_employee_no VARCHAR(32);

COMMENT ON COLUMN skill.declared_owner_name IS
    '匿名上传时上传者自称的归属人姓名,可空。**未经核实**,与 owner_user_id 指向的真实账号是两回事;'
        'owner_user_id = 1(system)表示无主待认领,此时前端展示这个自称值并标注未认领。'
        '认领后保留不清空,作为"上传时自称了谁"的历史线索';

COMMENT ON COLUMN skill.declared_owner_employee_no IS
    '匿名上传时上传者自称的归属人工号,可空。同名同姓在公司规模上是必然事件,只有姓名等于没有归属线索;'
        '同样未经核实。刻意**不**作为认领资格的门槛 —— 本地建号普遍没绑工号(线上三个账号 employee_no 全空),'
        '拿它当门槛会导致声明了工号的包谁都认领不了';
