-- skill-hub 初始表结构
-- 约定:不使用外键约束(与团队既有实践一致),关联完整性由应用层保证,只建关联列索引。
-- 搜索暂不建全文/trgm 索引:skill 量级在几百条,ILIKE 顺序扫描足够快;
-- 真到需要时再单独加迁移,不在这里预先加索引维护成本。

-- ============================================================
-- 通用:更新时间自动维护
-- ============================================================
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ============================================================
-- skill:技能元数据
-- ============================================================
CREATE TABLE skill (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(64)  NOT NULL,
    display_name   VARCHAR(128) NOT NULL,
    description    TEXT         NOT NULL,
    tags           TEXT[]       NOT NULL DEFAULT '{}',
    owner          VARCHAR(64)  NOT NULL,
    latest_version VARCHAR(32),
    created_by     VARCHAR(64)  NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE  skill                IS 'skill 元数据,一个 skill 对应多个版本';
COMMENT ON COLUMN skill.name           IS '唯一标识,kebab-case,与 SKILL.md frontmatter 的 name 一致';
COMMENT ON COLUMN skill.display_name   IS '展示名';
COMMENT ON COLUMN skill.description    IS '一句话描述,来自 frontmatter';
COMMENT ON COLUMN skill.tags           IS '标签数组,用于筛选';
COMMENT ON COLUMN skill.owner          IS '归属人';
COMMENT ON COLUMN skill.latest_version IS '最新版本号,冗余字段避免列表页 N+1';

CREATE UNIQUE INDEX uk_skill_name ON skill (name);

CREATE TRIGGER trg_skill_updated_at
    BEFORE UPDATE ON skill
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ============================================================
-- skill_version:技能版本与制品
-- ============================================================
CREATE TABLE skill_version (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id      BIGINT       NOT NULL,
    version       VARCHAR(32)  NOT NULL,
    artifact_key  VARCHAR(255) NOT NULL,
    sha256        CHAR(64)     NOT NULL,
    size_bytes    BIGINT       NOT NULL,
    allowed_tools TEXT[]       NOT NULL DEFAULT '{}',
    changelog     TEXT,
    created_by    VARCHAR(64)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE  skill_version               IS 'skill 的一个已发布版本';
COMMENT ON COLUMN skill_version.version       IS '语义化版本号';
COMMENT ON COLUMN skill_version.artifact_key  IS 'ArtifactStorage 中的制品键,与存储实现解耦';
COMMENT ON COLUMN skill_version.sha256        IS '制品摘要,渲染安装脚本时内嵌,客户端下载后当场校验';
COMMENT ON COLUMN skill_version.size_bytes    IS '制品字节数';
COMMENT ON COLUMN skill_version.allowed_tools IS 'SKILL.md 声明的 allowed-tools,安装前展示给使用者';

CREATE UNIQUE INDEX uk_skill_version ON skill_version (skill_id, version);
CREATE INDEX idx_skill_version_skill_id ON skill_version (skill_id);

CREATE TRIGGER trg_skill_version_updated_at
    BEFORE UPDATE ON skill_version
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ============================================================
-- install_bundle:一次安装选择,是"网页选一堆 -> 一条命令"的载体
-- ============================================================
CREATE TABLE install_bundle (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token      VARCHAR(32) NOT NULL,
    items      JSONB       NOT NULL,
    client     VARCHAR(32) NOT NULL,
    scope      VARCHAR(16) NOT NULL,
    created_by VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL
);

COMMENT ON TABLE  install_bundle            IS '安装单:一次勾选生成一个 token,对应一条安装命令';
COMMENT ON COLUMN install_bundle.token      IS '短随机串,出现在安装 URL 中';
COMMENT ON COLUMN install_bundle.items      IS 'skill 与版本清单 JSON 数组';
COMMENT ON COLUMN install_bundle.client     IS '目标客户端:claude / codex / workbuddy';
COMMENT ON COLUMN install_bundle.scope      IS '安装级别:global / project';
COMMENT ON COLUMN install_bundle.expires_at IS '过期时间,防止旧命令长期流传装到过期版本';

CREATE UNIQUE INDEX uk_install_bundle_token ON install_bundle (token);
CREATE INDEX idx_install_bundle_expires_at ON install_bundle (expires_at);
